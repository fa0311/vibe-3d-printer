"""はめあい・穴径の補正値。パーツはここの値を使い、数値を直書きしない。

この A1 mini (0.4 mm ノズル) + Bambu PLA Basic + 0.20mm Standard で `parts/fit-test` を印刷して
確かめた値 (2026-11-18)。測定の詳細と読み方は parts/fit-test/README.md。

分かったこと:
- 平らな面どうしのはめあいは非常に正確。10 mm 角のペグが、片側 0.05 mm の角穴に「軽く押して入り、
  落ちない」、片側 0.10 mm の角穴に「すっと入り、自重で落ちる」。
- 外形は 10 mm 程度なら設計どおりに出る (10 mm 角のペグの実測が 10.0 mm)。
- 丸穴はノギスの読みで直径 0.4〜0.5 mm 小さい (呼び 3〜8 mm で一様)。ただし内寸の読みには
  0.2 mm ほどの「小さめ」が乗っている: ペグが 10.0 mm で設計 10.1 mm の角穴にしっくり入るので
  角穴はほぼ設計どおりなのに、同じ測り方で設計 10.6 mm の角穴は 10.3 mm と読めた。
  内寸の測定 (ジョウの傾き、挟む力) では普通に起きることで、0.1 mm 表示のノギスの精度の範囲内。
  差し引いた丸穴の本当の縮みは 0.2 mm 強。
- 外形は長い寸法ほど少し短く出る: 設計 80 mm が 79.6 mm、40 mm が 39.9 mm (0.25〜0.5 %)。
  100 mm を超える相手に合わせる寸法では、この分を見込むか、試し刷りで確かめる。
"""

from __future__ import annotations

CALIBRATED = True

# --- 丸穴 ---
# ノギスの読みでは平均 0.44 mm の縮み。内寸の測定に乗る「小さめ」(約 0.2 mm) を引いた値。
# 穴のある部品を最初に作ったとき、実物のねじや軸で合い具合を確かめて見直すこと。
HOLE_COMP = 0.25      # 丸穴の直径に足す量。垂直 (Z 軸方向) の穴向け

# --- 平らな面どうしのすき間 (片側あたり) ---
CLEAR_PRESS = 0.00    # 圧入: 叩き込む / 外れない (未実測。0.05 より詰めた推定値)
CLEAR_SNUG = 0.05     # しっくり: 軽く押して入り、逆さにしても落ちない (実測)
CLEAR_SLIDE = 0.10    # すべり: すっと入り、自重で抜ける。蓋・引き出し向け (実測)
CLEAR_LOOSE = 0.20    # ゆるい: 確実に入ればよい (0.15 以上は実測で「ゆるい」側)

# --- 印刷の都合 ---
NOZZLE = 0.4
LAYER = 0.2
MIN_WALL = 1.2        # 強度が要る壁の最小厚 (ノズル幅の3倍)
BED = (180.0, 180.0, 180.0)


def hole(d: float) -> float:
    """実寸 d の軸・ねじが通る丸穴のモデル上の直径。"""
    return d + HOLE_COMP


# メートルねじ: (通し穴, 直接ねじ込む下穴, キャップボルト頭径, 頭高さ, ナット二面幅, ナット厚)
_SCREWS = {
    "M2":   (2.4, 1.7, 3.8, 2.0, 4.0, 1.6),
    "M2.5": (2.9, 2.1, 4.5, 2.5, 5.0, 2.0),
    "M3":   (3.4, 2.6, 5.5, 3.0, 5.5, 2.4),
    "M4":   (4.5, 3.5, 7.0, 4.0, 7.0, 3.2),
    "M5":   (5.5, 4.4, 8.5, 5.0, 8.0, 4.7),
    "M6":   (6.6, 5.2, 10.0, 6.0, 10.0, 5.2),
}


def screw(size: str) -> dict[str, float]:
    """ねじ周りのモデル寸法 (補正込み)。size は "M3" など。"""
    through, tap, head_d, head_h, nut_af, nut_h = _SCREWS[size]
    return {
        "through": through + HOLE_COMP,          # 通し穴の直径
        "tap": tap + HOLE_COMP,                  # 樹脂に直接ねじ込む下穴の直径
        "head_d": head_d + HOLE_COMP + 0.3,      # 頭を沈めるザグリの直径 (これも丸穴なので縮む)
        "head_h": head_h + 0.2,                  # ザグリの深さ
        "nut_af": nut_af + 2 * CLEAR_SNUG,       # ナットポケットの二面幅
        "nut_h": nut_h + 0.3,                    # ナットポケットの深さ
    }
